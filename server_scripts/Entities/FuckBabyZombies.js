EntityEvents.spawned(event => {
    let entity = event.entity

    if (entity.type === 'minecraft:zombie') {
        let isBaby = entity.nbt.getBoolean('IsBaby')
        
        if (isBaby) {
            entity.mergeNbt({IsBaby: false})
        }
    }
})

